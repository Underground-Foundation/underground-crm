"""
robots.txt, generated by django-robots from the rules edited in the Django admin.

django-robots scopes its rules to the django.contrib.sites ``Site`` named by ``SITE_ID``.
That record's domain is edited by hand, separately from the Wagtail sites that actually
serve pages, and it stays "example.com" until somebody remembers to change it. The library
would otherwise build the absolute URL of the sitemap it advertises from that domain, so
this view takes the scheme and host from the request instead: the sitemap is served by the
very host that the crawler has just asked for robots.txt, and ``ALLOWED_HOSTS`` has already
vouched for that host.
"""

from robots.views import RuleList


class RequestHostRuleList(RuleList):
    def get_domain(self) -> str:
        return f"{self.request.scheme}://{self.request.get_host()}"


robots_txt_view = RequestHostRuleList.as_view()
